// Generate the catalog-to-implementation mapping table from the source of truth.
//
//   node scripts/gen-rule-map.mjs           # write docs/rule-map.md
//   node scripts/gen-rule-map.mjs --check   # verify the committed file is current
//
// WHY THIS EXISTS.  The published catalog (docs/TRANSLATION_RULES.md) numbers rules
// ENC1..CMP2 -- 38 of them, induced from the pattern machines.  src/engine/rules.ts
// carries 25 matcher entries whose ids are NOT the same names: several catalog rules
// collapse into one matcher that dispatches on the chosen container (UNION-pair covers
// PS2, FN3 and MS2), and one catalog rule can have more than one matcher (FN3-app and
// FN3-override).  A reader told to "check the rule against its implementation" cannot
// do so without this correspondence, so it is generated from the code rather than
// maintained by hand, and the doc goes stale loudly instead of silently.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(here, "..", "src", "engine", "rules.ts");
const OUT = path.join(here, "..", "docs", "rule-map.md");
const check = process.argv.includes("--check");

const src = fs.readFileSync(SRC, "utf8");
const lines = src.split("\n");

// Each rule is `{ id: "X", match: re(/.../), ...}` preceded by a `// ──` comment block
// that names the catalog rule(s) it realises.
const CATALOG = /\b(ENC|SET|FN|PS|MS|ST|CMP)\d+\b/g;
const rows = [];
for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(/\{\s*id:\s*"([A-Za-z0-9-]+)"/);
  if (!m) continue;
  // Walk back over the contiguous comment block above this entry.
  const comment = [];
  for (let j = i - 1; j >= 0 && lines[j].trim().startsWith("//"); j--)
    comment.unshift(lines[j].trim().replace(/^\/\/\s?/, "").replace(/^──\s*/, "").replace(/\s*──$/, ""));
  const text = comment.join(" ").trim();
  const named = [...new Set((text.match(CATALOG) ?? []))];
  // The Event-B shape is the part of the comment after the first colon, when present.
  const shape = (text.split(/:\s/).slice(1).join(": ") || text).replace(/\s+/g, " ").trim();
  rows.push({ id: m[1], catalog: named, shape });
}

const esc = (s) => s.replace(/\|/g, "\\|");
const body = rows.map((r) =>
  `| \`${r.id}\` | ${r.catalog.length ? r.catalog.map((c) => `\`${c}\``).join(", ") : "—"} | ${esc(r.shape)} |`
).join("\n");

const covered = [...new Set(rows.flatMap((r) => r.catalog))].sort();
const out = `<!-- GENERATED by scripts/gen-rule-map.mjs from src/engine/rules.ts — DO NOT EDIT -->
# Catalog rules and their implementation

The catalog in [TRANSLATION_RULES.md](TRANSLATION_RULES.md) numbers **38 rules** in seven
families. The engine implements them as **${rows.length} matcher entries** in
[\`src/engine/rules.ts\`](../src/engine/rules.ts). The two numberings differ on purpose:

* **One matcher can realise several catalog rules.** \`UNION-pair\` matches
  \`R ≔ R ∪ {a ↦ b}\` and then dispatches on the container chosen for \`R\`, so it is
  \`PS2\` for a pair-set, \`FN3\` for a function and \`MS2\` for a map-of-sets. \`CLEAR\`
  covers every family's "reset to empty" rule at once.
* **One catalog rule can need several matchers.** \`FN3\` appears as both \`FN3-app\`
  (\`f(k) ≔ v\`) and \`FN3-override\` (\`f ≔ f  {k ↦ v}\`), because Event-B spells the
  same update two ways.
* **Two families are not in this file at all.** \`ENC1\`–\`ENC6\` choose the container and
  live in [\`src/engine/encodingResolver.ts\`](../src/engine/encodingResolver.ts);
  \`ST1\`–\`ST5\` are structural (event → guarded \`bool\` method, typing guards dropped)
  and are applied by [\`src/engine/codeEmitter.ts\`](../src/engine/codeEmitter.ts) and
  \`translateEvent\` in [\`src/engine/ruleEngine.ts\`](../src/engine/ruleEngine.ts).

Catalog rules named by the matchers below: ${covered.map((c) => `\`${c}\``).join(", ")}.

| Implementation id | Catalog rule(s) | Shape it matches |
|---|---|---|
${body}

Guards and actions are matched by the same array: \`translateEvent\` tries every rule
once per clause, in the order above, and takes the first that matches. There is no
recursion into subexpressions — see the *catalog matches shapes, and does not nest*
limitation in the paper.
`;

if (check) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
  if (cur !== out) {
    console.error("docs/rule-map.md is STALE — run: node scripts/gen-rule-map.mjs");
    process.exit(1);
  }
  console.log(`docs/rule-map.md is current (${rows.length} matchers)`);
} else {
  fs.writeFileSync(OUT, out, "utf8");
  console.log(`wrote docs/rule-map.md — ${rows.length} matchers, ${covered.length} catalog rules named`);
}
