// node derive_baseline_net.mjs -- writes SensorScopeAodvNetwork.ned, the field
// [Config Baseline] runs on, from SensorScopeNetwork.ned.
//
// Why a second network: the field declares its nodes with a concrete type
// (`sink: SensorNode`), and a typename assignment applies only to a submodule
// declared with a parametric type (`<...> like ...`; OMNeT++ 6.3 manual,
// "typename pattern assignments"). `*.sink.typename = "..."` in the ini is
// silently ignored on this field -- measured 2026-10-19: the first Baseline runs
// recorded every node as inet.node.inet.SensorNode, with no aodv module. And
// NED forbids retyping an inherited submodule, so `extends` cannot do it either.
//
// So the baseline's network is DERIVED, never edited by hand: the same text with
// the network renamed and each node's type SensorNode -> BaselineAodvSensorNode.
// Positions (p= is the physical position) cannot drift from the measured field.
// Refuses unless exactly one network line and exactly nine node lines change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "SensorScopeNetwork.ned"), "utf8");
const lines = src.split(/\r?\n/);
let nets = 0, nodes = 0;
const out = lines.map((l) => {
  if (/^network SensorScopeNetwork\s*$/.test(l)) { nets++; return "network SensorScopeAodvNetwork"; }
  const m = /^(\s+)(sink|sensor\d+): SensorNode \{(.*)$/.exec(l);
  if (m) { nodes++; return `${m[1]}${m[2]}: BaselineAodvSensorNode {${m[3]}`; }
  return l;
});
if (nets !== 1 || nodes !== 9) {
  console.error(`REFUSE: expected 1 network line and 9 node lines, found ${nets} and ${nodes}`);
  process.exit(2);
}
const header = [
  "// GENERATED by derive_baseline_net.mjs from SensorScopeNetwork.ned -- do not edit.",
  "// The old field, for [Config Baseline]: every node is a BaselineAodvSensorNode",
  "// (BaselineAodv.ned). Only the network name and the nine node types differ.",
  "",
];
writeFileSync(join(here, "SensorScopeAodvNetwork.ned"), header.join("\n") + out.join("\n"));
console.log(`wrote SensorScopeAodvNetwork.ned: 1 network line and ${nodes} node lines changed`);
